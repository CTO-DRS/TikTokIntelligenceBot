def t(lang: str, key: str, **kwargs) -> str:
    """Translate `key` into `lang` with graceful fallbacks (never raises)."""
    primary = TRANSLATIONS.get(lang or "ar", TRANSLATIONS["ar"])
    text = primary.get(key) or TRANSLATIONS["en"].get(key) or key
    if kwargs:
        try:
            text = text.format(**kwargs)
        except (KeyError, IndexError, ValueError):
            pass
    return text
